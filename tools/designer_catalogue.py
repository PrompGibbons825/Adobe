"""Dev tool: write the designer-decisions catalogue for Vlatko (families with 4+ sizes).

    .venv/bin/python -m tools.designer_catalogue [--out PATH] [--haiku N]

For each family: the source (first member) and, per designer resize, the decisions in plain
words, plus one "likely reasoning" line generated by template from the measured decisions
(labelled inferred). A summary at the top reads the fitted trees' top splits and the decision
counts. --haiku N rewrites the first N reasoning lines with Bedrock Haiku (fed only the measured
decisions; tokens logged to /data/agents/work/designer/status/bedrock_tokens.jsonl).
"""

