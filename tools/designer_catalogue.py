import argparse
import collections
import json
import math
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from engine.smart import decisions as D  # noqa: E402
from tools.designer_fit import TREE_OUT, aspect_class, iter_families, member_to_design, tournament  # noqa: E402

OUT = Path("/home/vlatko/code/adobe-hackathon-2026/context/notes/2026-10-30-designer-decisions.md")
TOKENS = Path("/data/agents/work/designer/status/bedrock_tokens.jsonl")

ZONE = {"t": "top", "m": "middle", "b": "bottom", "l": "left", "c": "center", "r": "right"}
ARR = {"restack": "re-stacked the copy and the image vertically", "to_row": "put the copy beside the image",
       "to_split": "split the canvas into an image panel beside the copy", "overlay": "moved the copy onto the image"}
LAYOUT = {"stack": "stacked", "row": "side-by-side", "split": "split-panel", "overlay": "copy-on-image",
          "single": "single-block"}
PHOTO = {"bleed": "kept the photo full-bleed", "crop_bleed": "cropped the photo to fill the canvas",
         "framed": "kept the photo framed inside the canvas"}


def zone_words(z: str) -> str:
    if z == "mc":
        return "the center"
    return "the " + ZONE[z[0]] + "-" + ZONE[z[1]] if z[0] != "m" else "the middle-" + ZONE[z[1]]


def shape_words(W, H) -> str:
    return f"{int(W)}x{int(H)} ({D._aspect_class(W / H)})"


def source_type(src: dict, f: dict) -> str:
    bits = []
    bits.append({"image": "full-bleed photo background", "shape": "flat color background",
                 "none": "no background"}[f["bg_kind"]])
    bits.append("copy on the photo" if f["copy_on_photo"] == "yes" else "copy off the photo")
    bits.append(LAYOUT[f["layout"]] + " layout")
    n_img = int(f["n_images"])
    bits.append("text only" if f["text_only"] else f"{n_img} image{'s' if n_img != 1 else ''}")
    bits.append(f"{int(f['n_text'])} text block{'s' if f['n_text'] != 1 else ''}")
    return ", ".join(bits)


def headline_factor(src: dict, out: dict):
    rm = D.roles(src)
    m = D.match(src, out)
    Ws, Hs = D._canvas(src)
    Wo, Ho = D._canvas(out)
    lin = math.sqrt(Wo * Ho / (Ws * Hs))
    for e in src["elements"]:
        if rm.get(e["id"]) == "headline" and m.get(e["id"]) is not None:
            return D._fs(m[e["id"]]) / max(1e-6, D._fs(e)) / lin
    return None


def words(src: dict, out: dict, dec: dict, keep: dict, f: dict) -> str:
    parts = []
    arr = dec.get("arrangement", "kept")
    parts.append(ARR.get(arr, f"kept the {LAYOUT[f['layout']]} layout"))
    if dec.get("photo") in PHOTO and keep.get("photo") != "none":
        parts.append(PHOTO[dec["photo"]] if dec["photo"] != keep.get("photo") or dec["photo"] == "bleed"
                     else PHOTO[dec["photo"]])
    hf = headline_factor(src, out)
    if hf is not None:
        parts.append(f"headline {hf:.1f}x relative" + (" (bigger)" if hf > 1.25 else " (smaller)" if hf < 0.8 else ""))
    for role, name in (("headline", "headline"), ("art", "logo/art"), ("hero", "main image"), ("small", "small print")):
        k = "anchor:" + role
        if k in dec:
            if dec[k] != keep.get(k):
                parts.append(f"{name} moved to {zone_words(dec[k])}")
    if dec.get("align") not in (None, keep.get("align"), "none"):
        parts.append(f"copy re-aligned {dec['align']}")
    if dec.get("emphasis") == "up":
        parts.append("headline emphasis raised")
    elif dec.get("emphasis") == "down":
        parts.append("headline emphasis lowered")
    if dec.get("group_kept") == "no":
        parts.append("broke up a source group")
    if dec.get("order_kept") == "no":
        parts.append("re-ordered the copy")
    if dec.get("coverage") != keep.get("coverage"):
        parts.append({"low": "left more empty space", "mid": "content fills about half the canvas",
                      "high": "content spread to fill the canvas"}[dec["coverage"]])
    drops = [k.split(":")[1] for k, v in dec.items() if k.startswith("drop:") and v != "no"]
    if drops:
        parts.append("dropped " + ", ".join(drops))
    return ", ".join(parts)


def reasoning(f: dict, resizes: list) -> str:
    """Template over the measured decisions of a family (inferred, not observed)."""
    big = [r for r in resizes if r["lac"] > 0.9]
    arr = collections.Counter(r["dec"].get("arrangement") for r in resizes)
    moved = sum(1 for r in resizes if r["dec"].get("anchor:headline") != r["keep"].get("anchor:headline"))
    hf = [r["hf"] for r in resizes if r["hf"] is not None]
    bits = []
    if arr.get("kept", 0) == len(resizes):
        bits.append(f"the {LAYOUT[f['layout']]} composition survives every size, so the designer kept it and rescaled")
    else:
        ch = [a for a in arr if a != "kept"]
        bits.append("the composition did not fit the " + ("extreme " if big else "") + "shapes, so the designer "
                    + " / ".join(ARR[a] for a in ch))
    if moved:
        bits.append(f"the headline was repositioned in {moved} of {len(resizes)} sizes to follow the new shape")
    if hf:
        g = math.exp(sum(math.log(max(1e-3, x)) for x in hf) / len(hf))
        if g > 1.2:
            bits.append(f"type was enlarged beyond plain scaling ({g:.1f}x) to stay readable in the smaller or narrower formats")
        elif g < 0.83:
            bits.append(f"type was shrunk relative to the canvas ({g:.1f}x) to fit the copy")
        else:
            bits.append("type scaled with the canvas")
    if f["bg_kind"] == "image":
        bits.append("the full-bleed photo anchors the brand look, so it stayed behind everything")
    return "; ".join(bits) + "."


def haiku(prompt: str):
    body = {"messages": [{"role": "user", "content": [{"text": prompt}]}],
            "inferenceConfig": {"maxTokens": 160, "temperature": 0.2}}
    r = subprocess.run(["aws", "--profile", "vlatlabs", "--region", "us-east-1", "bedrock-runtime", "converse",
                        "--model-id", "global.anthropic.claude-haiku-5-5", "--cli-input-json", json.dumps(body)],
                       capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        return None, None
    j = json.loads(r.stdout)
    txt = j["output"]["message"]["content"][0]["text"].strip()
    return txt, j.get("usage", {})


def tree_summary(trees: dict, decs=("arrangement", "anchor_row:headline", "anchor_col:headline", "photo",
                                    "scale:headline", "group_kept")) -> list:
    FEAT = {"abs_aspect_change": "|log aspect change|", "log_aspect_change": "signed log aspect change (target wider > 0)",
            "log_tgt_ar": "log target aspect", "log_src_ar": "log source aspect", "area_ratio": "log area ratio",
            "headline_share": "headline share of canvas", "hero_share": "hero image share", "n_text": "text blocks",
            "n_images": "images", "cut_n": "top-level XY-cut segments"}
    lines = []

    def cond(n, side):
        if "eq" in n:
            return f"{n['f']} {'is' if side == 'r' else 'is not'} {n['eq']}"
        return f"{FEAT.get(n['f'], n['f'])} {'>' if side == 'r' else '<='} {n['t']:.2f}"

    def leaves(n, path):
        if "leaf" in n:
            yield path, n["leaf"]
            return
        for side in ("l", "r"):
            yield from leaves(n[side], path + [cond(n, side)])

    for d in decs:
        t = trees.get(d)
        if not t:
            continue
        lines.append(f"- **{d}**: first split on {cond(t, 'r').rsplit(' ', 2)[0] if 'eq' not in t else t['f']}.")
        notable = [(p, lf) for p, lf in leaves(t, []) if lf["v"] not in ("=", "kept", "yes", "same") and lf["n"] >= 30]
        for p, lf in sorted(notable, key=lambda pl: -pl[1]["n"])[:4]:
            lines.append(f"  - if {' and '.join(p)} -> **{lf['v']}** ({lf['p']:.0%} of {lf['n']} training pairs)")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--haiku", type=int, default=0)
    a = ap.parse_args()
    tour = tournament()
    fams = [f for f in iter_families() if f["n_sizes"] >= 4]
    blocks, counts = [], collections.Counter()
    by_type = collections.defaultdict(collections.Counter)
    n_haiku = 0
    for f in fams:
        designs = [member_to_design(m) for m in f["members"]]
        src = designs[0]
        Ws, Hs = D._canvas(src)
        feats0 = D.source_features(src, src)
        keep = D.keep_source(src)
        resizes = []
        for t in designs[1:]:
            ft = D.source_features(src, t)
            dec = D.decisions_of(src, t)
            Wt, Ht = D._canvas(t)
            resizes.append(dict(W=Wt, H=Ht, dec=dec, keep=keep, lac=ft["abs_aspect_change"], hf=headline_factor(src, t),
                                text=words(src, t, dec, keep, feats0)))
            stype = f"{feats0['bg_kind']} bg / {feats0['layout']}"
            by_type[(stype, aspect_class(ft["abs_aspect_change"]))][dec["arrangement"]] += 1
            counts[dec["arrangement"]] += 1
        reason = reasoning(feats0, resizes)
        src_label = "template"
        if n_haiku < a.haiku:
            prompt = ("A designer resized one graphic design to several canvas sizes. Measured decisions (from geometry):\n"
                      f"Source: {shape_words(Ws, Hs)}; {source_type(src, feats0)}.\n"
                      + "\n".join(f"- to {shape_words(r['W'], r['H'])}: {r['text']}" for r in resizes)
                      + "\nIn one sentence (max 40 words), state the most likely reasoning behind these decisions. "
                        "Use only the facts above; do not invent content.")
            txt, usage = haiku(prompt)
            if txt:
                reason, src_label = txt, "Haiku from the measured decisions"
                n_haiku += 1
                TOKENS.parent.mkdir(parents=True, exist_ok=True)
                with TOKENS.open("a") as fh:
                    fh.write(json.dumps({"t": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "agent": "tree",
                                         "model": "global.anthropic.claude-haiku-5-5", "family": f["fam"],
                                         **(usage or {})}) + "\n")
        b = [f"### {f['fam']}{' (tournament, eval-only)' if f['fam'] in tour else ''}",
             f"Source {shape_words(Ws, Hs)}: {source_type(src, feats0)}."]
        for r in resizes:
            b.append(f"- -> {shape_words(r['W'], r['H'])}: {r['text']}.")
        b.append(f"- *Likely reasoning (inferred, {src_label}):* {reason}")
        blocks.append("\n".join(b))
    trees = json.loads(TREE_OUT.read_text())["trees"] if TREE_OUT.exists() else {}
    head = ["# Designer decisions in Crello resizes (2026-10-30)", "",
            "Generated by `chameleon/tools/designer_catalogue.py` (branch exp/designer-tree) from "
            "`/data/agents/work/crello-wide/families.jsonl` with `engine/smart/decisions.py`. Geometry only: "
            "every decision below is measured from element boxes and font sizes; the reasoning lines are inferred.",
            "", f"{len(fams)} families with 4+ sizes; source = first member; {sum(counts.values())} resizes.", "",
            "## Summary", "", "Arrangement over all resizes: "
            + ", ".join(f"{k} {v}" for k, v in counts.most_common()) + ".", "",
            "Arrangement by source type and aspect change (small < 0.3 <= mid <= 0.9 < large):", "",
            "| source type | aspect change | resizes | kept | restack | to_row | to_split | overlay |",
            "|---|---|---|---|---|---|---|---|"]
    for (st, ac), c in sorted(by_type.items(), key=lambda kv: (-sum(kv[1].values()))):
        if sum(c.values()) < 15:
            continue
        head.append(f"| {st} | {ac} | {sum(c.values())} | " + " | ".join(str(c.get(k, 0)) for k in
                                                                         ("kept", "restack", "to_row", "to_split", "overlay")) + " |")
    head += ["", "What the fitted trees (depth 4, min leaf 30, tournament families excluded) learned, in words. "
             "'=' leaves mean 'keep the source's own value'; only leaves that predict a change are listed:", ""]
    head += tree_summary(trees)
    head += ["", "## Families", ""]
    Path(a.out).write_text("\n".join(head) + "\n\n" + "\n\n".join(blocks) + "\n")
    print(a.out, len(fams), "families", n_haiku, "haiku lines")


if __name__ == "__main__":
    main()
